use crate::{ArgInfo, Error};
use core::cell::Cell;

/// One argument of the generated help: its labels, descriptions and placement.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HelpEntry {
    /// The label of the help line, e.g. `<INPUT>` or `-o, --output <OUTPUT>`.
    pub label: &'static str,
    /// The label in the usage line for a positional argument, e.g. `[-- <REST>]`, empty for options.
    pub usage: &'static str,
    /// Whether the argument is positional.
    pub positional: bool,
    /// Whether the argument is hidden from the help.
    pub hidden: bool,
    /// Whether the argument is a `global` option, also listed in the help of subcommands.
    pub global: bool,
    /// The custom section of the argument, empty for the default `Arguments` or `Options` section.
    pub heading: &'static str,
    /// The explicit `display_order`, when `ordered` is set.
    pub order: usize,
    /// Whether the argument has an explicit `display_order`.
    pub ordered: bool,
    /// The description in the short help.
    pub short: &'static str,
    /// Whether the short description can be wrapped.
    pub short_wraps: bool,
    /// The description in the long help.
    pub long: &'static str,
    /// Whether the long description can be wrapped.
    pub long_wraps: bool,
}

impl HelpEntry {
    /// An empty entry, used to fill arrays before they are written.
    pub const EMPTY: HelpEntry = HelpEntry {
        label: "",
        usage: "",
        positional: false,
        hidden: true,
        global: false,
        heading: "",
        order: 0,
        ordered: false,
        short: "",
        short_wraps: true,
        long: "",
        long_wraps: true,
    };

    /// A generated flag of the parent, such as `-h, --help`.
    pub const fn reserved(label: &'static str, short: &'static str, long: &'static str) -> Self {
        HelpEntry {
            label,
            short,
            long,
            hidden: false,
            ..HelpEntry::EMPTY
        }
    }
}

/// Parsing state shared by a struct with the structs it flattens and its subcommands.
#[derive(Debug, Clone, Copy)]
pub struct Context<'a, 'r> {
    /// The last raw argument, used to recognise negative numbers.
    pub raw: Option<&'r Cell<Option<&'a str>>>,
    /// Whether a `last` positional exists, so that arguments after `--` skip the other positionals.
    pub last: bool,
    /// Whether every option and positional accepts negative numbers.
    pub negative_numbers: bool,
    /// Whether a positional argument before the struct is still missing.
    pub blocked: bool,
    /// The short and long help of every command of the parsed command tree, in pre-order.
    pub helps: &'static [&'static str],
    /// The index of the command being parsed in the command tree.
    pub node: usize,
}

impl<'a, 'r> Context<'a, 'r> {
    /// The context of the struct being parsed.
    pub const fn new(raw: Option<&'r Cell<Option<&'a str>>>) -> Self {
        Context {
            raw,
            last: false,
            negative_numbers: false,
            blocked: false,
            helps: &[],
            node: 0,
        }
    }

    /// The context of a struct with subcommands, whose command tree has the help texts `helps`.
    pub const fn with_helps(self, helps: &'static [&'static str]) -> Self {
        Context { helps, ..self }
    }

    /// The context of a flattened struct.
    pub const fn child(self, last: bool, negative_numbers: bool, blocked: bool) -> Self {
        Context {
            last: self.last || last,
            negative_numbers: self.negative_numbers || negative_numbers,
            blocked: self.blocked || blocked,
            ..self
        }
    }

    /// The context of the subcommand at index `node` of the command tree.
    pub const fn command(self, node: usize) -> Self {
        Context {
            raw: self.raw,
            last: false,
            negative_numbers: false,
            blocked: false,
            helps: self.helps,
            node,
        }
    }

    /// The short or long help of the command being parsed.
    pub fn help(&self, long: bool) -> &'static str {
        let index = 2 * self.node + usize::from(long);
        self.helps.get(index).copied().unwrap_or_default()
    }
}

/// Offers an argument to the `global` options of the parents of a subcommand. Returns `Ok(true)`
/// when one of them consumed it.
pub type Globals<'g, 'a, I> = dyn FnMut(getargs::Arg<&'a str>, &mut getargs::Options<&'a str, I>) -> Result<bool, Error<'a>>
    + 'g;

/// The [`Globals`] of a command without parents.
pub fn no_globals<'a, I: Iterator<Item = &'a str>>(
    _argument: getargs::Arg<&'a str>,
    _options: &mut getargs::Options<&'a str, I>,
) -> Result<bool, Error<'a>> {
    Ok(false)
}

/// Per-struct parsing API generated by `#[derive(GetArgs)]`, used by the parser of the struct itself
/// and of the structs that flatten it with `#[command(flatten)]`.
#[diagnostic::on_unimplemented(
    message = "`{Self}` does not derive `GetArgs`",
    label = "flattened fields and newtype subcommand variants must wrap a type deriving `GetArgs`"
)]
pub trait Args<'a>: Sized {
    /// Values collected while parsing, before required arguments and relations are checked.
    type State;

    /// Help entries of the arguments, flattened structs included, in field order.
    const ENTRIES: &'static [HelpEntry];
    /// Short option names and aliases, flattened structs included.
    const SHORTS: &'static [char];
    /// Long option names and aliases, flattened structs included.
    const LONGS: &'static [&'static str];
    /// Whether each positional argument is optional, flattened structs included, in field order.
    const POSITIONALS: &'static [bool];
    /// Whether a positional argument uses `last`, flattened structs included.
    const LAST: bool;
    /// Whether an argument falls back to an environment variable, flattened structs included.
    type Env: EnvFlag;
    /// Whether a visible argument has a long help text, flattened structs included.
    const HAS_LONG_HELP: bool;
    /// Public metadata of the arguments, flattened structs included, in field order.
    const ARGS: &'static [ArgInfo];
    /// [`ARGS`](Self::ARGS) followed by the generated flags of the struct itself.
    const COMMAND_ARGS: &'static [ArgInfo];
    /// The help of the struct when it is used as a command or a subcommand.
    const COMMAND: CommandHelp;

    /// Returns the state before any argument is parsed.
    fn init() -> Self::State;

    /// Whether every positional argument, flattened structs included, has a value.
    fn filled(state: &Self::State) -> bool;

    /// Offers one argument to the struct. Returns `Ok(true)` when it was consumed, `Ok(false)`
    /// when the struct does not handle it.
    fn try_arg<I: Iterator<Item = &'a str>>(
        state: &mut Self::State,
        argument: getargs::Arg<&'a str>,
        options: &mut getargs::Options<&'a str, I>,
        context: Context<'a, '_>,
        globals: &mut Globals<'_, 'a, I>,
    ) -> Result<bool, Error<'a>>;

    /// Offers one argument given after a subcommand to the `global` options of the struct,
    /// flattened structs included. Returns `Ok(true)` when it was consumed.
    fn try_global<I: Iterator<Item = &'a str>>(
        state: &mut Self::State,
        argument: getargs::Arg<&'a str>,
        options: &mut getargs::Options<&'a str, I>,
        context: Context<'a, '_>,
    ) -> Result<bool, Error<'a>>;

    /// Checks relations, reads environment variables, applies defaults and builds the struct.
    fn finish<E: FnMut(&str) -> Option<&'a str>>(
        state: Self::State,
        env: &mut E,
    ) -> Result<Self, Error<'a>>;
}

/// Per-enum parsing API generated by `#[derive(Subcommand)]`, used by the struct holding the
/// `#[command(subcommand)]` field.
#[diagnostic::on_unimplemented(
    message = "`{Self}` cannot be used as a subcommand because it does not derive `Subcommand`",
    label = "subcommand field type must derive `Subcommand`"
)]
pub trait Subcommand<'a>: Sized {
    /// The parsed arguments of the selected subcommand, before they are checked.
    type State;
    /// Whether a subcommand reads environment variables.
    type Env: EnvFlag;

    /// The subcommands, in variant order.
    const COMMANDS: &'static [CommandEntry];
    /// The names and visible aliases of the visible subcommands, used for suggestions.
    const NAMES: &'static [&'static str];
    /// The names of the visible subcommands, reported when a required subcommand is missing.
    const VISIBLE: &'static [&'static str];
    /// The public metadata of the subcommands, in variant order.
    const INFOS: &'static [crate::CommandInfo];

    /// Parses the rest of the command line as the subcommand called `name`. Returns `Ok(None)`
    /// when no subcommand has this name or alias.
    fn try_command<I: Iterator<Item = &'a str>>(
        name: &'a str,
        options: &mut getargs::Options<&'a str, I>,
        context: Context<'a, '_>,
        globals: &mut Globals<'_, 'a, I>,
    ) -> Result<Option<Self::State>, Error<'a>>;

    /// Checks the arguments of the selected subcommand and builds the variant.
    fn finish<E: FnMut(&str) -> Option<&'a str>>(
        state: Self::State,
        env: &mut E,
    ) -> Result<Self, Error<'a>>;
}

/// The help of a struct deriving `GetArgs`, from its own `#[command(...)]` attributes.
#[derive(Debug, Clone, Copy)]
pub struct CommandHelp {
    /// The command name, used in the usage line when the struct is parsed on its own.
    pub name: &'static str,
    /// The `before_help` text, empty when there is none.
    pub before_help: &'static str,
    /// The `about` text, empty when there is none.
    pub about: &'static str,
    /// The `long_about` text, empty when there is none.
    pub long_about: &'static str,
    /// The `after_help` text, empty when there is none.
    pub after_help: &'static str,
    /// The width to wrap at, or `0` not to wrap.
    pub term_width: usize,
    /// Whether the struct has the generated `-h`/`--help` flag.
    pub help_flag: bool,
    /// Whether the struct has the generated `-V`/`--version` flag.
    pub version: bool,
    /// The help entries of the arguments, flattened structs included.
    pub entries: &'static [HelpEntry],
    /// Whether a visible argument has a long help text.
    pub has_long_help: bool,
    /// The short option names and aliases.
    pub shorts: &'static [char],
    /// The long option names and aliases.
    pub longs: &'static [&'static str],
    /// The subcommands, empty when the struct has no `#[command(subcommand)]` field.
    pub commands: &'static [CommandEntry],
    /// Whether a subcommand must be given.
    pub subcommand_required: bool,
    /// The public metadata of the subcommands.
    pub infos: &'static [crate::CommandInfo],
}

/// The public metadata of a subcommand whose arguments are `args`, the generated help flag
/// included, and whose struct has the help `command`.
pub const fn subcommand_info(
    name: &'static str,
    about: &'static str,
    long_about: &'static str,
    args: &'static [ArgInfo],
    command: &CommandHelp,
) -> crate::CommandInfo {
    crate::CommandInfo::new(name)
        .about(about)
        .long_about(long_about)
        .args(args)
        .commands(command.infos)
        .subcommand_required(command.subcommand_required)
}

/// One subcommand of an enum deriving `Subcommand`.
#[derive(Debug, Clone, Copy)]
pub struct CommandEntry {
    /// The name of the subcommand.
    pub name: &'static str,
    /// The description in the `Commands` section, visible aliases included.
    pub description: &'static str,
    /// The `about` text of the subcommand help.
    pub about: &'static str,
    /// The `long_about` text of the subcommand help.
    pub long_about: &'static str,
    /// Whether the subcommand is hidden from the `Commands` section.
    pub hidden: bool,
    /// The help of the struct holding the arguments of the subcommand.
    pub command: &'static CommandHelp,
}

/// The separator between the description of a subcommand and its visible aliases.
pub const fn separator(about: &str, aliases: &str) -> &'static str {
    if about.is_empty() || aliases.is_empty() {
        ""
    } else {
        " "
    }
}

/// Number of commands in the tree rooted at `command`, itself included.
pub const fn nodes(command: &CommandHelp) -> usize {
    let mut total = 1;
    let mut index = 0;
    while index < command.commands.len() {
        total += nodes(command.commands[index].command);
        index += 1;
    }
    total
}

/// Index in the command tree of the subcommand `index` of `commands`, whose parent is at `parent`.
pub const fn node(commands: &[CommandEntry], parent: usize, index: usize) -> usize {
    let mut node = parent + 1;
    let mut before = 0;
    while before < index {
        node += nodes(commands[before].command);
        before += 1;
    }
    node
}

/// Whether a subcommand in `commands`, nested ones included, uses the short option `short`.
pub const fn commands_use_short(commands: &[CommandEntry], short: char) -> bool {
    let mut index = 0;
    while index < commands.len() {
        let command = commands[index].command;
        if contains_short(command.shorts, short)
            || (command.help_flag && short == 'h')
            || commands_use_short(command.commands, short)
        {
            return true;
        }
        index += 1;
    }
    false
}

/// Whether a subcommand in `commands`, nested ones included, uses the long option `long`.
pub const fn commands_use_long(commands: &[CommandEntry], long: &str) -> bool {
    let mut index = 0;
    while index < commands.len() {
        let command = commands[index].command;
        if contains_long(command.longs, long)
            || (command.help_flag && str_eq(long, "help"))
            || commands_use_long(command.commands, long)
        {
            return true;
        }
        index += 1;
    }
    false
}

/// Reads the next argument, converting the errors of `getargs`.
pub fn next_arg<'a, I: Iterator<Item = &'a str>>(
    options: &mut getargs::Options<&'a str, I>,
) -> Result<Option<getargs::Arg<&'a str>>, Error<'a>> {
    options.next_arg().map_err(|error| match error {
        getargs::Error::DoesNotRequireValue(getargs::Opt::Short(short)) => {
            Error::UnexpectedValue(crate::Opt::Short(short))
        }
        getargs::Error::DoesNotRequireValue(getargs::Opt::Long(long)) => {
            Error::UnexpectedValue(crate::Opt::Long(long))
        }
        _ => Error::InvalidArguments,
    })
}

/// The error for an argument that no field consumed, suggesting one of `longs` for a long option.
pub fn unexpected<'a>(argument: getargs::Arg<&'a str>, longs: &[&[&'static str]]) -> Error<'a> {
    match argument {
        getargs::Arg::Positional(value) => Error::UnexpectedArgument(value),
        getargs::Arg::Short(short) => Error::UnknownOption {
            option: crate::Opt::Short(short),
            suggestion: None,
        },
        getargs::Arg::Long(long) => Error::UnknownOption {
            option: crate::Opt::Long(long),
            suggestion: crate::suggest::suggest(long, longs),
        },
    }
}

/// Parses the rest of the command line as the arguments of the subcommand `T`, handling its help
/// flag and offering the arguments it does not consume to the `global` options of its parents.
pub fn command<'a, T: Args<'a>, I: Iterator<Item = &'a str>>(
    options: &mut getargs::Options<&'a str, I>,
    context: Context<'a, '_>,
    globals: &mut Globals<'_, 'a, I>,
) -> Result<T::State, Error<'a>> {
    let mut state = T::init();
    while let Some(argument) = next_arg(options)? {
        if T::COMMAND.help_flag {
            match argument {
                getargs::Arg::Short('h') => return Err(Error::Help(context.help(false))),
                getargs::Arg::Long("help") => return Err(Error::Help(context.help(true))),
                _ => {}
            }
        }
        if T::try_arg(&mut state, argument, options, context, globals)? {
            continue;
        }
        if globals(argument, options)? {
            continue;
        }
        let reserved: &[&'static str] = if T::COMMAND.help_flag { &["help"] } else { &[] };
        return Err(unexpected(argument, &[T::LONGS, reserved]));
    }
    Ok(state)
}

/// Type-level flag telling whether a struct reads environment variables.
pub trait EnvFlag {
    /// `Self` or `Other`.
    type Or<Other: EnvFlag>: EnvFlag;
}

/// The struct reads environment variables.
pub struct UsesEnv;

/// The struct does not read environment variables.
pub struct NoEnv;

impl EnvFlag for UsesEnv {
    type Or<Other: EnvFlag> = UsesEnv;
}

impl EnvFlag for NoEnv {
    type Or<Other: EnvFlag> = Other;
}

/// Implemented when `parse` and `from_args` can read the environment variables of a struct whose
/// flattened structs and subcommands have the [`EnvFlag`] `F`.
#[diagnostic::on_unimplemented(
    message = "a flattened struct or a subcommand reads environment variables, which requires the `std` feature of `getargs-derive`",
    label = "`parse` and `from_args` read the process environment",
    note = "enable the `std` feature of `getargs-derive`, or call `parse_with_env` or `from_args_with_env` with a lookup function"
)]
pub trait EnvSupport<F> {}

impl<T: ?Sized> EnvSupport<NoEnv> for T {}

#[cfg(feature = "std")]
impl<T: ?Sized> EnvSupport<UsesEnv> for T {}

/// An environment lookup that finds no variable.
