/// Whether `list` contains `short`.
pub const fn contains_short(list: &[char], short: char) -> bool {
    let mut index = 0;
    while index < list.len() {
        if list[index] == short {
            return true;
        }
        index += 1;
    }
    false
}

/// Whether `list` contains `long`.
pub const fn contains_long(list: &[&str], long: &str) -> bool {
    let mut index = 0;
    while index < list.len() {
        if str_eq(list[index], long) {
            return true;
        }
        index += 1;
    }
    false
}

/// Whether `first` and `second` share a short name.
pub const fn shares_short(first: &[char], second: &[char]) -> bool {
    let mut index = 0;
    while index < first.len() {
        if contains_short(second, first[index]) {
            return true;
        }
        index += 1;
    }
    false
}

/// Whether `first` and `second` share a long name.
pub const fn shares_long(first: &[&str], second: &[&str]) -> bool {
    let mut index = 0;
    while index < first.len() {
        if contains_long(second, first[index]) {
            return true;
        }
        index += 1;
    }
    false
}

/// Whether no required positional argument follows an optional one.
pub const fn positionals_ordered(parts: &[&[bool]]) -> bool {
    let mut seen_optional = false;
    let mut part = 0;
    while part < parts.len() {
        let mut index = 0;
        while index < parts[part].len() {
            if parts[part][index] {
                seen_optional = true;
            } else if seen_optional {
                return false;
            }
            index += 1;
        }
        part += 1;
    }
    true
}

